-- 1. BOOKINGS TABLE
create table if not exists public.bookings (
    id bigint generated by default as identity primary key,
    booking_id text not null unique,
    veh_name text not null,
    category text default 'car',
    days integer not null default 1,
    pickup_hub text not null,
    pickup_datetime timestamptz not null,
    return_datetime timestamptz not null,
    base_price numeric not null,
    delivery_fee numeric default 0,
    insurance_fee numeric default 0,
    extra_services numeric default 0,
    has_driver boolean default false,
    driver_cost numeric default 0,
    total_amount numeric not null,
    advance_paid numeric not null,
    balance_due numeric not null,
    customer_name text not null,
    customer_phone text not null,
    customer_email text,
    license_no text,
    status text not null default 'Confirmed',
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 2. BREAKDOWN TICKETS TABLE
create table if not exists public.tickets (
    id bigint generated by default as identity primary key,
    ticket_id text not null unique,
    vehicle text not null,
    issue text not null,
    phone text not null,
    location text not null,
    notes text,
    is_urgent boolean default false,
    status text not null default 'Ticket raised',
    created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. CUSTOMER REVIEWS TABLE
create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    name text not null,
    text text not null,
    stars integer not null check (stars >= 1 and stars <= 5),
    created_at timestamptz default timezone('utc'::text, now()) not null
);

