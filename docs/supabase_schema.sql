-- ==========================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Enables public web visitors to insert & read bookings/tickets/reviews safely
-- ==========================================================

alter table public.bookings enable row level security;
alter table public.tickets enable row level security;
alter table public.reviews enable row level security;

-- BOOKINGS: Allow visitors to create bookings & read their own booking by booking_id
create policy "Allow anonymous insert into bookings"
    on public.bookings for insert
    to anon, authenticated
    with check (true);

create policy "Allow anonymous select from bookings"
    on public.bookings for select
    to anon, authenticated
    using (true);

-- TICKETS: Allow visitors to raise breakdown tickets and check status
create policy "Allow anonymous insert into tickets"
    on public.tickets for insert
    to anon, authenticated
    with check (true);

create policy "Allow anonymous select from tickets"
    on public.tickets for select
    to anon, authenticated
    using (true);

-- REVIEWS: Allow public to read and add reviews
create policy "Allow anonymous insert into reviews"
    on public.reviews for insert
    to anon, authenticated
    with check (true);

create policy "Allow anonymous select from reviews"
    on public.reviews for select
    to anon, authenticated
    using (true);
